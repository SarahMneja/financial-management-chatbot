def table_en_markdown(table):
    """Transforme un tableau brut en texte markdown lisible."""

    grille = [
        [(cellule or "").replace("\n", " ").strip() for cellule in rangee]
        for rangee in table
    ]

    largeur = max(len(r) for r in grille)
    grille = [
        r + [""] * (largeur - len(r))
        for r in grille
    ]

    entete = "| " + " | ".join(grille[0]) + " |"
    separateur = "| " + " | ".join(["---"] * largeur) + " |"
    corps = [
        "| " + " | ".join(r) + " |"
        for r in grille[1:]
    ]

    return "\n".join([entete, separateur] + corps)

