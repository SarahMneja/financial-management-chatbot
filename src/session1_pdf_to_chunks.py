import re

def nettoyer(texte):
    """Normalise le texte extrait d'un PDF."""
    texte = texte.replace("\u2019", "'")
    texte = "".join(ch for ch in texte if ch.isprintable() or ch == " ")
    texte = re.sub(r"(\w)-\s+(\w)", r"\1\2", texte)
    return re.sub(r"\s+", " ", texte).strip()


