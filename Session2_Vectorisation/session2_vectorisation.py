def verifier_longueurs(chunks, modele):
    """Compare la taille des chunks a la capacite du modele."""

    capacite = modele.max_seq_length

    tailles = [
        c["metadata"].get("n_tokens", 0)
        for c in chunks
    ]

    depassent = sum(
        1 for t in tailles
        if t > capacite
    )

    print(f"  Capacite du modele : {capacite} tokens")
    print(f"  Chunk le plus long : {max(tailles)} tokens")
    print(
        f"  Mediane            : "
        f"{sorted(tailles)[len(tailles) // 2]} tokens"
    )

    if depassent:
        part = depassent / len(chunks) * 100

        print(
            f"\n  ATTENTION : {depassent} chunks sur "
            f"{len(chunks)} ({part:.0f} %) depassent "
            f"la capacite."
        )

        print("  Ils seraient coupes, et la fin du texte perdue.")

    else:
        print("\n  Tous les chunks tiennent dans le modele.")

    return depassent


