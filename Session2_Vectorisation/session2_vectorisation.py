def recherche_semantique(question, index, chunks, modele, n=3):
    """
    Recherche les n chunks les plus proches d'une question.
    """

    # Transformer la question en vecteur
    vecteur_question = modele.encode(
        [question],
        normalize_embeddings=True
    )

    vecteur_question = np.asarray(
        vecteur_question,
        dtype="float32"
    )

    # Recherche FAISS
    scores, indices = index.search(
        vecteur_question,
        n
    )

    resultats = []

    for score, indice in zip(scores[0], indices[0]):
        resultats.append({
            "score": float(score),
            "chunk": chunks[int(indice)],
            "position": int(indice)
        })

    return resultats

