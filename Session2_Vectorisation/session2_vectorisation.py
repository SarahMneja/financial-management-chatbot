def charger_chunks(chemin):
    """Lit le fichier JSONL : une ligne = un chunk."""

    if not chemin.exists():
        print(f"ERREUR : {chemin} est introuvable.")
        sys.exit(1)

    chunks = []

    with open(chemin, encoding="utf-8") as fichier:
        for ligne in fichier:
            ligne = ligne.strip()

            if ligne:
                chunks.append(json.loads(ligne))

    return chunks


